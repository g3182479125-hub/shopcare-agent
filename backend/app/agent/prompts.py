def build_text_response_user_prompt(payload: dict) -> str:
    import json

    return "请用自然、有温度、像真人客服的中文，基于以下结构化上下文回复用户：\n" + json.dumps(
        payload,
        ensure_ascii=False,
        default=str,
    )
